"""Write-only encrypted STT eval log store — ti-qi76c.

Own SQLite file (not shared with roster.db or call_cards.db) holding sealed
(NaCl SealedBox) per-call transcript blobs for future model eval/training use.
Deliberately exposes exactly one method, ``append`` — no read/select/decrypt
path exists anywhere in this class, on this connection, or in this module.
That absence *is* the safety property: nothing short of editing this file to
add a new method could ever let the daemon (or anything running as the
daemon's user) recover plaintext from its own database. Only an operator
holding the offline NaCl private key generated by ``iris.eval_log_keygen``
can open a sealed entry, and only outside this process entirely.
"""
from __future__ import annotations

import sqlite3
import threading
import time
from pathlib import Path

_DEFAULT_PATH = Path.home() / ".local" / "share" / "iris" / "eval_log.db"

_DDL = """
CREATE TABLE IF NOT EXISTS eval_log_entries (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id   TEXT NOT NULL,
    key_version  INTEGER NOT NULL,
    sealed_blob  BLOB NOT NULL,
    created_at   REAL NOT NULL
);
CREATE INDEX IF NOT EXISTS eval_log_by_session ON eval_log_entries(session_id);
"""


class EvalLogStore:
    """SQLite WAL store for sealed per-call transcript blobs.

    Thread-safe via threading.Lock + check_same_thread=False, same convention
    as AfterStore/CallCardStore. Constructed fresh at each call site (see
    CallCardHost.stop_session) rather than held on self, so collaborators in
    tests that mock everything else never touch a real DB file.
    """

    def __init__(self, db_path: str | Path | None = None) -> None:
        path = Path(db_path) if db_path is not None else _DEFAULT_PATH
        path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = sqlite3.connect(str(path), check_same_thread=False)
        self._lock = threading.Lock()
        with self._lock:
            self._conn.execute("PRAGMA journal_mode=WAL")
            self._conn.executescript(_DDL)
            self._conn.commit()

    def append(self, session_id: str, key_version: int, sealed_blob: bytes) -> None:
        with self._lock:
            self._conn.execute(
                """
                INSERT INTO eval_log_entries (session_id, key_version, sealed_blob, created_at)
                VALUES (?, ?, ?, ?)
                """,
                (session_id, key_version, sealed_blob, time.time()),
            )
            self._conn.commit()
